#!/usr/bin/env python3
"""
Extracts the QCF v4 Basmala glyph outlines from QCF4_Hafs_01 into
src/lib/utils/basmala-paths.ts, so SurahHeader can draw the Basmala as inline
SVG instead of as a font glyph.

Why not just use the font: the Basmala is one glyph roughly 25,000 font units
(~10 em) wide, against 1–4 em for every other glyph in the set. Windows'
rasterizer mangles it — the artwork comes out squeezed together with long
horizontal streaks running off to the left — while the ordinary word glyphs
from the very same font render fine. FreeType (Linux) draws it correctly,
which is why it went unnoticed. An SVG path never goes near a font
rasterizer, so it renders the same everywhere.

Three codepoints carry Basmala artwork in the v4 data (U+F8D6 for almost every
Surah; U+F8D7 and the narrower U+F8DD on a few pages). All three are emitted,
keyed by the character page_line_word.glyph_v4 stores, so the header can keep
rendering exactly the glyph the layout data names.

Requires fontTools and brotli (the font is WOFF2):
    python3 -m venv /tmp/venv && /tmp/venv/bin/pip install fonttools brotli
    /tmp/venv/bin/python scripts/generate-basmala-paths.py

Re-run whenever static/fonts/mushaf-v4/QCF4_Hafs_01_W.woff2 is re-vendored.
"""

from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "static/fonts/mushaf-v4/QCF4_Hafs_01_W.woff2"
OUT = ROOT / "src/lib/utils/basmala-paths.ts"
CODEPOINTS = (0xF8D6, 0xF8D7, 0xF8DD)


def main() -> None:
    font = TTFont(FONT)
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    upem = font["head"].unitsPerEm
    hhea = font["hhea"]

    entries = []
    for cp in CODEPOINTS:
        name = cmap[cp]
        pen = SVGPathPen(glyphs, ntos=lambda n: str(round(n)))
        glyphs[name].draw(pen)
        advance = font["hmtx"][name][0]
        entries.append(
            f"  '\\u{{{cp:04X}}}': {{\n"
            f"    advance: {advance},\n"
            f"    d: '{pen.getCommands()}',\n"
            f"  }},"
        )

    OUT.write_text(
        "// Generated by scripts/generate-basmala-paths.py from QCF4_Hafs_01 — do not\n"
        "// edit by hand. See that script for why the Basmala is drawn as SVG.\n"
        "//\n"
        "// Coordinates are font units, y-up (the font's own space), so the path\n"
        "// has to be flipped to draw in SVG's y-down space.\n"
        "\n"
        "export interface BasmalaPath {\n"
        "  /** Horizontal advance, font units. */\n"
        "  advance: number;\n"
        "  d: string;\n"
        "}\n"
        "\n"
        f"export const BASMALA_UNITS_PER_EM = {upem};\n"
        f"export const BASMALA_ASCENT = {hhea.ascent};\n"
        f"export const BASMALA_DESCENT = {-hhea.descent};\n"
        "\n"
        "/** Keyed by the glyph character page_line_word.glyph_v4 stores. */\n"
        "export const BASMALA_PATHS: Record<string, BasmalaPath> = {\n"
        + "\n".join(entries)
        + "\n};\n"
    )
    print(f"Wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
